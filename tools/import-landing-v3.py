#!/usr/bin/env python3
"""Import the supplied Dietfit capture as a self-contained static landing page.

Usage: python3 tools/import-landing-v3.py [capture-directory]
No Next.js server, image optimizer, or Capture Studio replay server is needed.
The supplied React components retain their original Rive/scroll controllers.
"""

import html
import json
import re
import shutil
import sys
from pathlib import Path
from urllib.parse import parse_qs

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "dietfit-health-2026-10-27T03-18-56-616Z"
COPY_OVERRIDES = {
    "Meet Dietfit's Intermittent Fasting tracker. Choose a fasting schedule that fits your routine, and let Dietfit keep track of your fasting and eating windows. So you always know when to eat, when to fast, and how you're doing.":
        "Choose your schedule. Dietfit tracks when to fast and eat.",
}


def replace_once(text, before, after, label):
    if text.count(before) != 1:
        raise ValueError(f"{label}: expected one matching signature; capture version changed")
    return text.replace(before, after, 1)


def import_capture(source):
    manifest = json.loads((source / ".capture-index.json").read_text())
    page = (source / "index.html").read_text()
    if '<html lang="en"' not in page:
        raise ValueError("Expected the supplied English Dietfit landing capture")

    # Keep the existing Vietnamese page available through the language switch.
    vietnamese = ROOT / "vi" / "index.html"
    if not vietnamese.exists():
        original = (ROOT / "index.html").read_text()
        if '<html lang="vi"' not in original:
            raise ValueError("Cannot locate the existing Vietnamese homepage")
        vietnamese.parent.mkdir(parents=True, exist_ok=True)
        original = original.replace('href="./"', 'href="/vi/"')
        original = re.sub(r'((?:src|href|poster)=")\./', r'\1/', original)
        vietnamese.write_text(original.replace('href="/"', 'href="/vi/"'))

    variants_on_disk = {
        variant["file"]
        for variants in manifest["variants"].values()
        for variant in variants
    }
    for asset in (source / "landing").rglob("*"):
        relative = asset.relative_to(source)
        if not asset.is_file():
            continue
        if relative.as_posix() in variants_on_disk:
            # Drop only replay filenames generated by an earlier import.
            (ROOT / relative).unlink(missing_ok=True)
            continue
        # Some responsive assets exist in the capture but were omitted from
        # its variant index. Restore their original names too (notably Rive).
        canonical = re.sub(r"~[0-9a-f]{8}(?=\.[^.]+$)", "", relative.as_posix())
        target = ROOT / canonical
        if target != ROOT / relative:
            (ROOT / relative).unlink(missing_ok=True)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(asset, target)
    shutil.copytree(source / "_next" / "static", ROOT / "_next" / "static", dirs_exist_ok=True)
    shutil.copy2(source / "favicon.ico", ROOT / "favicon.ico")

    # Materialize query-string captures under their original asset filenames.
    # Image variants become ordinary files at the original image URL; use the
    # largest available capture so retina and wide screens keep their quality.
    images = {}
    for original, variants in manifest["variants"].items():
        if original == "_next/image":
            for variant in variants:
                query = parse_qs(variant["search"])
                image = query["url"][0]
                width = int(query.get("w", ["0"])[0])
                if image not in images or width > images[image][0]:
                    images[image] = (width, source / variant["file"])
        elif not original.startswith("en/"):
            target = ROOT / original
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source / variants[0]["file"], target)
    for image, (_, captured) in images.items():
        if not image.startswith("/") or ".." in Path(image).parts:
            raise ValueError(f"Unexpected asset URL: {image}")
        target = ROOT / image.lstrip("/")
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(captured, target)

    image_chunk = ROOT / "_next/static/chunks/992-f3b65e3ec12251a2.js"
    code = image_chunk.read_text()
    code = replace_once(
        code,
        'return r.path+"?url="+encodeURIComponent(n)+"&w="+i+"&q="+l+(n.startsWith("/_next/static/media/"),"")',
        'return n',
        "static image loader",
    )
    image_chunk.write_text(code)

    # Navigation must load existing static About/Blog pages, rather than ask a
    # nonexistent Next.js server for React Server Component responses.
    link_chunk = ROOT / "_next/static/chunks/2158-829e61f8f0a0d44e.js"
    code = link_chunk.read_text()
    code = replace_once(code, "prefetch:_=null", "prefetch:_=!1", "disable RSC prefetch")
    code = replace_once(
        code,
        'e.preventDefault(),u.default.startTransition(()=>{if(a){let e=!1;if(a({preventDefault:()=>{e=!0}}),e)return}(0,h.dispatchNavigateAction)(r||t,o?"replace":"push",null==i||i,n.current)})',
        'e.preventDefault(),o?location.replace(r||t):location.assign(r||t)',
        "static page navigation",
    )
    code = code.replace("window.__csNavigate(t)", "location.assign(t)")
    link_chunk.write_text(code)

    # Do not import the capture's analytics account into the local project.
    layout = ROOT / "_next/static/chunks/app/[locale]/layout-ec02e63ed3e01c38.js"
    code = layout.read_text()
    code = re.sub(r'let i="phc_[^"]+";', 'let i="";', code)
    code = replace_once(code, "t.GoogleAnalytics=function(e){", "t.GoogleAnalytics=function(e){return null;", "captured analytics")
    layout.write_text(code)

    # Remove capture instrumentation; retain the original HTML, hydration data,
    # components, and their scroll-driven Rive, video, and carousel behavior.
    page = re.sub(r'<script id="(?:local-replay-[^"]+|capture-studio-[^"]+)"[^>]*>.*?</script>\s*', "", page, flags=re.S)
    page = re.sub(r'<style id="capture-studio-[^"]+"[^>]*>.*?</style>', "", page, flags=re.S)
    page = re.sub(r' data-(?:cs-block|capture-studio-hidden)="[^"]*"', "", page)
    page = re.sub(r'<link[^>]*href="https://www.googletagmanager.com/[^>]*>', "", page)
    # This legacy polyfill was not included in the source capture; modern
    # browsers use the complete captured application bundle.
    page = re.sub(r'<script[^>]*src="[^"]*polyfills-[^"]*"[^>]*></script>', "", page)

    def image_url(match):
        query = parse_qs(html.unescape(match.group(1)))
        original = query.get("url", [""])[0]
        if original not in images:
            raise ValueError(f"Missing captured image: {original}")
        return original

    page = re.sub(r'/_next/image\?([^\s"<>]+)', image_url, page)
    # User-supplied Home CTA photograph; update SSR and Flight together.
    page = page.replace("/landing/v3/images/final-cta-us-en-user-photo.webp",
                        "/assets/images/final-cta-shared-table.webp")
    # Keep visible copy and its hydration messages in sync on every import.
    for original, replacement in COPY_OVERRIDES.items():
        page = page.replace(original, replacement)
    from streak_card import apply_streak_card
    page = apply_streak_card(page)
    from diary_card import apply_diary_card
    page = apply_diary_card(page)
    from progress_card import apply_progress_card
    page = apply_progress_card(page)
    from fasting_card import apply_fasting_card
    page = apply_fasting_card(page)
    from photo_cards import apply_photo_cards
    page = apply_photo_cards(page)
    card_copy_style = '<link rel="stylesheet" href="/styles/dietfit-card-copy.css">'
    if card_copy_style not in page:
        page = page.replace("</head>", card_copy_style + "\n</head>", 1)
    # Keep server-rendered and hydrated metadata in agreement.
    page = page.replace("https://dietfit.health/og/home.jpg?v=3", "https://dietfit.health/assets/og/og-home.jpg")
    page = page.replace("<head>", '<head>\n<!-- Dietfit landing v3: imported with tools/import-landing-v3.py -->\n', 1)
    (ROOT / "en" / "index.html").write_text(page)
    (ROOT / "index.html").write_text(page)
    from localize_home_cards import localize_cards
    localize_cards()
    if (ROOT / "en/benchmarks/index.html").exists():
        from import_benchmarks import update_navigation
        update_navigation()
    print(f"Imported Dietfit landing v3 from {source.name}; {len(images)} static images")


if __name__ == "__main__":
    import_capture(Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else DEFAULT_SOURCE)
